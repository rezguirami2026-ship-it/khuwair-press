// Builds src/fonts/fonts.css from the installed @fontsource packages:
// only the arabic + latin subsets of the weights we draw with, woff2 only (keeps the single-file build small).
import { readFileSync, writeFileSync } from 'node:fs';

const FAMILIES = {
  'amiri': [400, 700],
  'aref-ruqaa': [400, 700],
  'reem-kufi': [400, 500, 600, 700],
  'tajawal': [400, 500, 700, 800],
  'ibm-plex-sans-arabic': [400, 500, 600, 700]
};
const SUBSETS = ['arabic', 'latin'];

let out = '/* Generated by scripts/gen-fonts.mjs — do not edit by hand. Fonts: SIL Open Font License 1.1. */\n';
for (const [pkg, weights] of Object.entries(FAMILIES)) {
  for (const w of weights) {
    const css = readFileSync(`node_modules/@fontsource/${pkg}/${w}.css`, 'utf8');
    for (const block of css.split(/(?=\/\* )/)) {
      const sub = (block.match(/^\/\* [a-z-]+?-((?:latin-ext|latin|arabic))-\d+-normal \*\//) || [])[1];
      if (!SUBSETS.includes(sub)) continue;
      out += block
        .replace(/url\(\.\/files\/([^)]+?\.woff2)\) format\('woff2'\), url\([^)]+\) format\('woff'\)/,
          `url(../../node_modules/@fontsource/${pkg}/files/$1) format('woff2')`)
        .replace('font-display: swap', 'font-display: block')
        .trim() + '\n\n';
    }
  }
}
writeFileSync('src/fonts/fonts.css', out);
console.log('fonts.css:', (out.match(/@font-face/g) || []).length, 'faces');
